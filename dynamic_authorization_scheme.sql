-- View all registered components with their authorizations
SELECT c.app_id,
       c.page_id,
       c.component_type,
       c.component_static_id,
       rc.role_static_id,
       rc.is_authorized
  FROM apex_auth_component c
  LEFT JOIN apex_auth_role_component rc ON rc.apex_auth_component_id = c.id
 ORDER BY c.app_id, c.page_id, c.component_type, rc.role_static_id;

-- View user's effective permissions
SELECT c.page_id,
       c.component_type,
       c.component_static_id,
       aaur.user_name,
       aaur.role_static_id,
       rc.is_authorized
  FROM apex_auth_component c
  JOIN apex_auth_role_component rc ON rc.apex_auth_component_id = c.id
  JOIN apex_appl_acl_user_roles aaur ON aaur.role_static_id = rc.role_static_id
                                    AND aaur.application_id = c.app_id
 WHERE c.app_id = :APP_ID
   AND rc.is_authorized = 'Y'
 ORDER BY aaur.user_name, c.page_id;


