/*
================================================================================
  APEX APPLICATION SETUP INSTRUCTIONS
================================================================================

1. CREATE THE AUTHORIZATION SCHEME:
   --------------------------------
   a. In APEX Builder, go to: Shared Components > Authorization Schemes
   b. Click "Create"
   c. Set the following:
      - Name: Dynamic Authorization
      - Scheme Type: PL/SQL Function Returning Boolean
      - PL/SQL Function Body (copy the code below):

return 
dynamic_authorization.is_component_authorized(
  p_application_id => :APP_ID,
  p_page_id        => :APP_PAGE_ID,
  p_component_type => :APP_COMPONENT_TYPE,
  p_component_id   => :APP_COMPONENT_ID,
  p_component_name => :APP_COMPONENT_NAME
);

      - Evaluation Point: "Once per component" (recommended for production)
                          OR "Always (No Caching)" (for real-time changes)
      
      NOTE: The special bind variables :APP_COMPONENT_TYPE, :APP_COMPONENT_ID,
            and :APP_COMPONENT_NAME are ONLY available when Evaluation Point
            is set to "Once per component" or "Always (No Caching)"


2. ASSIGN TO COMPONENTS:
   ----------------------
   For each component (Page, Region, Button, Item, Menu) you want to control:
   a. Select the component in Page Designer
   b. In the Property Editor, find "Security" section
   c. Set "Authorization Scheme" to "Dynamic Authorization"
   

3. CREATE ADMINISTRATION PAGE (Optional but recommended):
   -------------------------------------------------------
   Create a page with two Interactive Grids to manage authorizations:
   
   Master IG Query (Components):
   
   SELECT id,
          app_id,
          page_id,
          component_type,
          component_static_id
     FROM apex_auth_component
    WHERE app_id = :APP_ID
    ORDER BY page_id, component_type, component_static_id

   Detail IG Query (Role Authorizations):
   
   SELECT id,
          apex_auth_component_id,
          role_static_id,
          is_authorized
     FROM apex_auth_role_component
    WHERE apex_auth_component_id = :P_COMPONENT_ID


4. SEED ROLE DATA (Example for default APEX ACL roles):
   -----------------------------------------------------
   After components are registered, you need to create role mappings.
   Example to seed all roles for a newly registered component:
*/

-- Example: Insert role mappings for all components (run after components are registered)
INSERT INTO apex_auth_role_component (apex_auth_component_id, role_static_id, is_authorized)
SELECT c.id, r.role_static_id, 'N'
  FROM apex_auth_component c
 CROSS JOIN (
    SELECT 'READER' AS role_static_id FROM dual
    UNION ALL
    SELECT 'CONTRIBUTOR' FROM dual
    UNION ALL
    SELECT 'ADMINISTRATOR' FROM dual
 ) r
 WHERE NOT EXISTS (
    SELECT 1 
      FROM apex_auth_role_component rc 
     WHERE rc.apex_auth_component_id = c.id 
       AND rc.role_static_id = r.role_static_id
 );

COMMIT;

/*
